"""Markdown files of a run folder: input.md, ANSWER.md and REASONING.md (spec §9)."""

from .case import CaseView

FAILURE = "Escalated: system failure"
ACTION_STATUS = {
    "approved": "recorded only; nothing was really sent or executed",
    "held": "awaiting property manager approval",
    "blocked": "blocked by the action gateway, not recorded",
    "duplicate": "dropped as a duplicate",
}


def input_markdown(view: CaseView) -> str:
    """The case exactly as the agent's tools expose it."""
    lines = [f"# Case {view.case_id}", ""]
    if view.raw:
        lines += ["Unfamiliar layout (raw mode). Files:", ""]
        lines += [f"- {name}" for name in view.files]
        return "\n".join(lines) + "\n"
    lines += ["## Case details", ""]
    lines += [f"- {key}: {value}" for key, value in view.details.items()]
    lines += ["", "## Initial request", "", view.initial_request, ""]
    if view.question:
        lines += ["## Question", "", view.question, ""]
    for heading, text in view.sections.items():
        lines += [f"## {heading}", "", text, ""]
    first, last = (
        (view.events[0].number, view.events[-1].number) if view.events else (0, 0)
    )
    lines += [f"## History (events {first} to {last})", ""]
    for event in view.events:
        lines += [
            f"### {event.timestamp} — event {event.number}",
            "",
            f"- Channel: {event.channel}",
            f"- From: {event.sender}",
            f"- To: {event.recipient}",
            "",
            event.body,
            "",
        ]
    lines += ["## Attachments", ""]
    lines += [f"- {name}" for name in view.attachments] or ["None."]
    return "\n".join(lines) + "\n"


def answer_markdown(result: dict, view: CaseView | None) -> str:
    failed = result["error"] is not None or result["next_move"] is None
    title = (
        FAILURE if failed else f"{result['next_move']}: {_one_line(result['summary'])}"
    )
    actions = result["actions"]
    lines = [
        f"# Case {result['id']}: {title}",
        "",
        "<!-- Generated by pm-agent, never edited by hand. -->",
        "",
        "## What the system received",
        "",
        _received(result, view),
        "",
        "## Decision",
        "",
    ]
    if failed:
        lines += [f"{FAILURE}: {result['error'] or 'no decision was submitted'}."]
    else:
        lines += [f"Next move: **{result['next_move']}**.", "", result["summary"]]
        if result["answer_to_question"]:
            lines += ["", f"Answer to the question: {result['answer_to_question']}"]
    lines += ["", "## Actions taken", ""]
    lines += [_action(a) for a in actions] or ["None."]
    lines += ["", "## Escalated", ""]
    lines += _escalated(result, actions, failed)
    lines += ["", "## What failed", ""]
    failures = [
        f"- {a['tool']} {a['status']} ({a['rule']}): {a['reason']}"
        for a in actions
        if a["status"] in ("blocked", "duplicate")
    ]
    if result["error"]:
        failures.insert(0, f"- System failure: {result['error']}")
    lines += failures or ["Nothing."]
    lines += ["", "## Final result", ""]
    held = sum(a["status"] == "held" for a in actions)
    recorded = sum(a["status"] == "approved" for a in actions)
    outcome = FAILURE if failed else f"Next move {result['next_move']}"
    lines += [
        (
            f"{outcome}. {recorded} action(s) recorded, {held} awaiting property "
            f"manager approval. Cost ${result['cost_usd']:.4f}, "
            f"{result['latency_s']:.1f} s."
        )
    ]
    return "\n".join(lines) + "\n"


def reasoning_markdown(result: dict) -> str:
    lines = [f"# Case {result['id']}: reasoning", ""]
    reasoning = result["reasoning"]
    if reasoning is None:
        return "\n".join(lines + [f"{FAILURE}: {result['error']}"]) + "\n"
    for key, heading in (
        ("facts", "Facts"),
        ("conflicts", "Conflicts"),
        ("missing", "Missing"),
        ("options_rejected", "Options rejected"),
    ):
        lines += [f"## {heading}", ""]
        lines += [f"- {item}" for item in reasoning.get(key) or []] or ["None."]
        lines += [""]
    lines += ["## Uncertainty", "", reasoning.get("uncertainty") or "None stated."]
    return "\n".join(lines) + "\n"


def _received(result: dict, view: CaseView | None) -> str:
    if view is None:
        return f"Case folder `{result['case_path']}` (could not be loaded)."
    if view.raw:
        return (
            f"Case folder `{result['case_path']}` in an unfamiliar layout: "
            f"{len(view.files)} file(s) read directly."
        )
    through = result["visible_through_event"]
    events = f"events 1 to {through}" if through else f"all {len(view.events)} events"
    return (
        f"Case `{result['case_path']}` ({result['view_mode']} mode) at "
        f"{view.details.get('Property', 'an unknown property')}: the initial request, "
        f"{events} and {len(view.attachments)} attachment(s)."
    )


def _action(action: dict) -> str:
    args = action["args"]
    status = ACTION_STATUS[action["status"]]
    if action["tool"] == "send_message":
        return (
            f"- **send_message** to {args.get('to')} ({args.get('purpose')}), {status}.\n"
            f"  Subject: {args.get('subject')}\n\n"
            + "\n".join(
                f"  > {line}" for line in str(args.get("body", "")).splitlines()
            )
        )
    if action["tool"] == "escalate":
        return f"- **escalate**, {status}: {args.get('reason')}"
    details = ", ".join(f"{key}: {value}" for key, value in args.items())
    return f"- **{action['tool']}** ({details}), {status}."


def _escalated(result: dict, actions: list[dict], failed: bool) -> list[str]:
    lines = []
    if failed:
        lines += [
            (
                f"{FAILURE}. A property manager must handle this case by hand: "
                f"{result['error'] or 'no decision was submitted'}."
            )
        ]
    for action in actions:
        if action["tool"] == "escalate" and action["status"] in ("approved", "held"):
            note = action["args"].get("handover_note") or {}
            lines += [f"Reason: {action['args'].get('reason')}", ""]
            for key in ("known", "conflicts", "done", "needed"):
                lines += [f"- **{key.capitalize()}:** {note.get(key, '')}"]
    held = [a for a in actions if a["status"] == "held"]
    if held:
        lines += ["", "Awaiting property manager approval:"]
        lines += [f"- {a['tool']}: {a['reason']}" for a in held]
    return lines or [
        f"Nothing: the next move is {result['next_move']} and needs no human."
    ]


def _one_line(text: str) -> str:
    line = " ".join(str(text).split())
    return line if len(line) <= 100 else line[:97] + "..."
